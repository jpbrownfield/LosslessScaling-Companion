import threading
import ctypes
import time
import unittest
from types import SimpleNamespace
from unittest.mock import Mock, patch

from companion.core.models import AppConfig, HotkeyConfig
from companion.core.state import AppState
from companion.services.hotkey_listener import GlobalHotkeyListener, WM_HOTKEY, OVERLAY_HOTKEY_BASE


class GlobalHotkeyListenerTests(unittest.TestCase):
    def test_overlay_message_reaches_callback_and_reregisters_after_restart(self):
        received = threading.Event()
        listener = GlobalHotkeyListener(SimpleNamespace(config=AppConfig()), AppState(), lambda: None)
        listener.set_overlay_actions({"overlay_toggle": {
            "binding": "ctrl+shift+f22", "callback": received.set,
        }})
        for _ in range(2):
            received.clear()
            try:
                listener.start()
                self.assertEqual(listener.overlay_registered, {"overlay_toggle": "ctrl+shift+f22"})
                self.assertTrue(ctypes.windll.user32.PostThreadMessageW(
                    listener._thread_id, WM_HOTKEY, OVERLAY_HOTKEY_BASE, 0
                ))
                self.assertTrue(received.wait(timeout=1))
            finally:
                listener.stop()
            self.assertEqual(listener.overlay_registered, {})

    def native_listener(self):
        manager = SimpleNamespace(config=SimpleNamespace(
            override_lossless_hotkey=False,
            global_hotkey=HotkeyConfig(modifiers=["ctrl", "alt"], key="s"),
            override_hotkey=HotkeyConfig(),
        ))
        state = AppState()
        state.is_scaling_active = True
        state.scaling_target_pid, state.scaling_target_hwnd = 42, 84
        callback = Mock()
        return GlobalHotkeyListener(manager, state, lambda: None, callback), callback

    def test_native_observer_matches_modifiers_ignores_injection_and_coalesces_hold(self):
        listener, callback = self.native_listener()
        listener._native_binding = (3, ord("S"))
        fake = Mock()
        fake.GetAsyncKeyState.side_effect = lambda vk: 0x8000 if vk in (0x11, 0x12) else 0
        with patch("companion.services.hotkey_listener.ctypes.windll.user32", fake):
            listener._observe_native_key(0x100, ord("S"), 0x10)
            callback.assert_not_called()
            listener._observe_native_key(0x100, ord("S"), 0)
            listener._observe_native_key(0x100, ord("S"), 0)
            callback.assert_called_once_with(42, 84)
            listener._observe_native_key(0x101, ord("S"), 0)
            fake.GetAsyncKeyState.return_value = 0
            fake.GetAsyncKeyState.side_effect = None
            listener._observe_native_key(0x100, ord("S"), 0)
            self.assertEqual(callback.call_count, 1)
            listener._observe_native_key(0x101, ord("S"), 0)
            listener.state.is_scaling_active = False
            fake.GetAsyncKeyState.side_effect = lambda vk: 0x8000 if vk in (0x11, 0x12) else 0
            listener._observe_native_key(0x104, ord("S"), 0)
            self.assertEqual(callback.call_count, 1)

    def test_native_observer_installs_and_releases_when_proxy_enabled(self):
        listener, _ = self.native_listener()
        # A read-only hook: no keyboard input is generated by this test.
        try:
            listener.start()
            self.assertTrue(listener._native_hook)
            listener.profile_manager.config.override_lossless_hotkey = True
            listener.profile_manager.config.override_hotkey = HotkeyConfig(key="f23", modifiers=[])
            listener.refresh()
            deadline = time.monotonic() + 1
            while listener._native_hook and time.monotonic() < deadline:
                time.sleep(0.01)
            self.assertIsNone(listener._native_hook)
        finally:
            listener.stop()
        self.assertIsNone(listener._native_proc)

    def test_blocking_message_loop_refreshes_and_stops(self):
        manager = SimpleNamespace(config=SimpleNamespace(
            override_lossless_hotkey=False,
            override_hotkey=HotkeyConfig(activation_delay_ms=0),
        ))
        listener = GlobalHotkeyListener(manager, AppState(), lambda: None)

        listener.start()
        thread = listener._thread
        self.assertIsNotNone(listener._thread_id)
        self.assertTrue(thread and thread.is_alive())

        listener.refresh()
        listener.stop()

        self.assertFalse(thread and thread.is_alive())
        self.assertIsNone(listener._thread_id)

    def test_dispatch_coalesces_overlapping_hotkey_events(self):
        callback_started = threading.Event()
        allow_callback_to_finish = threading.Event()
        calls = []

        def callback():
            calls.append(True)
            callback_started.set()
            allow_callback_to_finish.wait(timeout=1)

        manager = SimpleNamespace(config=SimpleNamespace(
            override_lossless_hotkey=False,
            override_hotkey=HotkeyConfig(),
        ))
        listener = GlobalHotkeyListener(manager, AppState(), callback)

        listener._dispatch()
        self.assertTrue(callback_started.wait(timeout=1))
        listener._dispatch()
        allow_callback_to_finish.set()

        self.assertEqual(calls, [True])

    def test_dispatch_waits_for_override_keys_to_be_released(self):
        callback_called = threading.Event()
        manager = SimpleNamespace(config=SimpleNamespace(
            override_lossless_hotkey=True,
            override_hotkey=HotkeyConfig(
                modifiers=["alt"], key="l", activation_delay_ms=75
            ),
        ))
        listener = GlobalHotkeyListener(manager, AppState(), callback_called.set)

        started = time.monotonic()
        listener._dispatch()

        self.assertTrue(callback_called.wait(timeout=1))
        self.assertGreaterEqual(time.monotonic() - started, 0.06)


if __name__ == "__main__":
    unittest.main()
